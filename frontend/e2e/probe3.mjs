import { chromium } from "playwright";
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
page.on("pageerror", (e) => console.log("pageerror:", String(e).slice(0,200)));
page.on("console", (m) => { if (m.type()==="error") console.log("console:", m.text().slice(0,150)); });
await page.goto("http://127.0.0.1:8177/", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(3500);
await page.locator(".composer-input").click();
await page.keyboard.type("hi kiko, who are you?", { delay: 8 });
await page.locator(".send-btn").click();
await page.waitForTimeout(14000);
await page.locator(".composer-input").click();
await page.keyboard.type("set a timer for 2 minutes called demo", { delay: 8 });
await page.waitForTimeout(700);
const val = await page.locator(".composer-input").inputValue();
console.log("VALUE:", JSON.stringify(val));
console.log("disabled:", await page.locator(".send-btn").isDisabled());
await page.screenshot({ path: "/tmp/opencode/kiko-e2e/probe3.png" });
await browser.close();
